# --------------------------------------------------------------------------------------------------------------------- 2. the rules

def _chain(error: str, cls: str = "RUNTIME_ERROR_OTHER", phase: str = "repo_run") -> list[dict]:
    return [{"error": error, "class": cls, "attribution": "REPO", "phase": phase, "cleared_by": None}]


def _attempt(n: int = 1, stderr: str = "", env=(), gate: str = "[]") -> dict:
    return {"attempt_number": str(n), "diff_text": "", "gate_decision": "PASS", "gate_violations": gate, "exit_code": 1, "stdout_tail": "", "stderr_tail": stderr,
            "env_delta": list(env), "origin": "model"}


def test_docker_names_the_missing_container_runtime_and_prefers_the_recorded_line():
    rec = {"verdict": "BLOCKED", "error_chain": _chain("run.sh: 7: docker: not found"), "attempts": [_attempt(stderr="docker: Cannot connect to the Docker daemon at unix:///x.sock")]}
