def test_every_rule_returns_a_verbatim_error_line():
    """For every committed record with a blocker (all harness versions), a finding's error_line is a line of that record's own output."""
    checked = 0
    for p in sorted((ROOT / "runs").glob("**/*.json")):
        if p.stat().st_size > 30_000_000:
            continue
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if not isinstance(d, dict):
            continue
        if "result" in d and isinstance(d["result"], dict) and "error_chain" in d["result"]:
            rec = _record(str(p.relative_to(ROOT)))
        elif "diffs" in d and "error_chain" in d:
            rec = _record(str(p.relative_to(ROOT)))
        else:
            continue
        if rec["verdict"] in ("RUNS_CLEAN", "RUNS_AFTER_REPAIR"):
            continue
        finding = diagnosis.diagnose(rec)
        if finding is None:
            continue
        checked += 1
        blob = diagnosis.strip_ansi(_evidence(rec)) + "\n" + diagnosis.strip_ansi(json.dumps(rec.get("attempts"), ensure_ascii=False))
        assert finding.error_line.strip() in blob, (p.name, finding.error_line)
    assert checked >= 14


