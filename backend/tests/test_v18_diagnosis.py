def test_a_missing_repository_extension_needs_the_gates_own_message():
    chain = _chain("ModuleNotFoundError: No module named 'ops._ext'", "DEP_MISSING")
    gate = "[{'rule': 'ENV_SHADOWS_REPO_MODULE', 'reason': \"env_delta[0]: 'ops' matches the repository's own module 'ops'; installing an unrelated PyPI package\"}]"
    f = diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": chain, "attempts": [_attempt(gate=gate)]})
    assert f.cause == "REPO_EXTENSION_NOT_BUILT" and "`ops` is the repository's own package" in f.sentence
    assert diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": chain, "attempts": []}) is None  # a dotted name alone proves nothing about the repository


def test_a_missing_module_with_no_pypi_release_versus_one_that_does_not_build():
    chain = _chain("ModuleNotFoundError: No module named 'foo'", "DEP_MISSING")
    add = [{"op": "add", "package": "foo", "version": "1.0"}]
    no_dist = diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": chain, "attempts": [_attempt(stderr="ERROR: No matching distribution found for foo==1.0", env=add)]})
    assert no_dist.cause == "MODULE_NOT_ON_PYPI" and "no installable release" in no_dist.sentence
    bad = diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": chain, "attempts": [_attempt(stderr="  File \"x.py\", line 2\nSyntaxError: invalid syntax", env=add)]})
    assert bad.cause == "VENDORED_MODULE_MISSING"
    nothing = diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": chain, "attempts": [_attempt(stderr="Successfully installed foo-1.0", env=add)]})
    assert nothing is None  # an install that worked says nothing about the module being vendored


def test_the_retired_git_protocol_needs_both_the_failure_and_the_url():
    tail = "  Running command git clone --quiet git://github.com/a/b.git /tmp/x\n  fatal: unable to connect to github.com:\n"
    f = diagnosis.diagnose({"verdict": "BLOCKED", "error_chain": _chain("error: subprocess-exited-with-error", "DEP_BUILD_FAILED"), "attempts": [_attempt(stderr=tail)]})
