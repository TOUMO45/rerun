def test_a_stored_indeterminate_stop_now_carries_a_blocker():
    """Until v1.7.2 `derived_record` never gave `blocker.report` the reason, so the out-of-sample scan's AutoDoc and mud-pi records have `blocker: null`."""
    reason = "ENTRYPOINT_NEEDS_ARGS: the command failed because it did not get the arguments it reads (`main.py: error: the following arguments are required: -file`); a human must supply them"
    out = derived_record("INDETERMINATE", [], [], reason, None)["blocker"]
    assert out["class"] == "ENTRYPOINT_NEEDS_ARGS" and out["error_line"] == "main.py: error: the following arguments are required: -file"
    unclear = derived_record("INDETERMINATE", [], [], "ENTRYPOINT_UNCLEAR: no runnable entrypoint discoverable in recon: no candidate scripts found", None)["blocker"]
    assert unclear["class"] == "ENTRYPOINT_UNCLEAR" and unclear["fixable_by"] == "human" and "name the command" in unclear["next_action"]


