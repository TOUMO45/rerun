"""harness-v1.8: the evidence-driven diagnosis (owner, 2026-10-07: "the fixable_by / 'human must supply' text must be derived from the record's evidence, not a
fixed sentence per class"), the docker / conda stops (T9), the classifier's evidence line (T10) and NLTK as missing data (D-54).

Three layers:
  1. THE KEY. `reports/dev/v18/diagnosis_key.json` was committed before `diagnosis.py` existed, from facts verified in the triage. Each of the 14 blocker records of the
     21 held-out entries (now DEV-CONTAMINATED) is regenerated by `blocker.report` and judged by the key's regexes. On the harness-v1.7.2 code every one of the nine
     "was wrong" entries fails (the old text is a fixed per-class sentence).
  2. THE RULES, on small inputs, with the negative cases that keep a rule from firing on a keyword (`docker` in a comment, `Resource` in another library's message).
  3. THE PLUMBING: the stop-early pipeline, `derived_record` carrying `indeterminate_reason`, the classifier's evidence line.
"""

from __future__ import annotations

