def test_pips_wrapper_line_is_not_the_evidence_when_the_cause_precedes_it():
    stderr = ("  Running command git clone --filter=blob:none --quiet git://github.com/a/b.git /tmp/pip-x\n"
              "  fatal: unable to connect to github.com:\n  github.com[0: 140.82.121.3]: errno=Connection timed out\n\n"
              "  error: subprocess-exited-with-error\n  \n  × git clone git://github.com/a/b.git did not run successfully.\n  │ exit code: 128\n"
              "  ╰─> See above for output.\n\nerror: subprocess-exited-with-error\n")
    c = classifier.classify(1, stderr, "")
    assert c.code == "DEP_BUILD_FAILED" and c.evidence == "fatal: unable to connect to github.com:"


