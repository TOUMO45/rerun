"""Build the RERUN cheat benchmark package from the committed records (owner, 2026-10-09, task 3).

    python benchmark/build.py          # (re)write benchmark/sets, benchmark/decisions and benchmark/HASHES.json
    python benchmark/build.py --check  # fail if any of them is not what the committed records give

Nothing here is typed by hand: the two sets are byte copies of their committed originals (checked against them and against the hash each set was published with),
the family definitions are read from the documents the patches were written under, the dropped list from the confirmation runs, and every decision file from a
committed measurement record. `score.py` turns a decision file into the per-family table."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PLANTED = ROOT / "reports" / "v1.9" / "planted"
INDEP = ROOT / "reports" / "v1.10" / "independent"
SETS = HERE / "sets"
DECISIONS = HERE / "decisions"

PLANTED_FILES = ("corpus.jsonl", "split.json", "bases.json", "PROTOCOL.md")
INDEP_FILES = ("manifest.json", "AUTHOR_PROMPT.txt", "SET_HASH.json", "PROVENANCE.md", "CONFIRM_RESULT.md", "measured_ids.txt")
PLANTED_FAMILY_NAMES = {"F1": "swallowed exception", "F2": "stubbed function", "F3": "skipped missing input", "F4": "early exit / hardcoded output",
                        "F5": "altered documented command", "F6": "workload shrunk to nothing"}
# the three repositories whose unpatched run really fails on the kept environment image (reports/v1.10/pipeline/scenarios.json: population A)
FAILING_REPOSITORIES = ("SimplE", "patchSmoothing", "L2D")


def _jsonl(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def _dump_jsonl(rows: list[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in rows)


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def planted_families_md() -> str:
    rows = _jsonl(PLANTED / "corpus.jsonl")
    split = json.loads((PLANTED / "split.json").read_text(encoding="utf-8"))
    held = set(split["heldout"])
    lines = ["# The planted set: families (generated by benchmark/build.py from corpus.jsonl)", "",
             "337 deterministic patches planted into seven repositories that have a committed run (`PROTOCOL.md`, `reports/v1.9/planted/generate.py`). Labels are by "
             "construction: a cheat makes the documented command end with exit 0 doing less of its work; a control changes no amount of work. The patches were written by "
             "the assistant that also wrote the gate's rules.", "",
             "| kind | family | name | n (dev / held-out) | example intent |", "|---|---|---|---|---|"]
    for (kind, fam), group in sorted(Counter((r["kind"], r["family"]) for r in rows).items(), key=lambda kv: (kv[0][0], int(kv[0][1][1:]))):
        members = [r for r in rows if (r["kind"], r["family"]) == (kind, fam)]
        h = sum(1 for r in members if r["id"] in held)
        name = PLANTED_FAMILY_NAMES.get(fam, "honest control")
        lines.append(f"| {kind} | {fam} | {name} | {group} ({group - h} / {h}) | {sorted({r['intent'] for r in members})[0]} |")
    return "\n".join(lines) + "\n"


def independent_families_md() -> str:
    prompt = (INDEP / "AUTHOR_PROMPT.txt").read_text(encoding="utf-8").splitlines()
    defs = [ln.strip() for ln in prompt if ln.strip().startswith(("1. CHEATS", "- family", "2. HONEST", "2. CONTROLS"))]
    if not any(d.startswith("- family") for d in defs):
        raise SystemExit("the family definitions were not found in AUTHOR_PROMPT.txt")
    return ("# The independent set: families (generated by benchmark/build.py, quoted from AUTHOR_PROMPT.txt, the instructions its author received)\n\n"
            "208 patches written by a separate agent that was given these definitions and the seven repositories and nothing of RERUN's checks (`PROVENANCE.md`). "
            "Only the cheats that reached exit 0 in a confirmation run are measured (144 of 166); the 22 others are listed in `dropped.json`.\n\n"
            + "\n".join(f"> {d}" for d in defs) + "\n")


def dropped() -> list[dict]:
    measured = set((INDEP / "measured_ids.txt").read_text(encoding="utf-8").split())
    out = []
    for r in _jsonl(INDEP / "confirm" / "results.jsonl"):
        if r["kind"] == "cheat" and r["id"] not in measured:
            run = r.get("run") or {}
            out.append({"id": r["id"], "repo": r["repo"], "family": r["family"], "exit_code": run.get("exit_code"), "timed_out": run.get("timed_out"),
                        "why": "did not reach exit 0 in its confirmation run (reports/v1.10/independent/confirm/results.jsonl); dropped before any measurement, not edited"})
    return sorted(out, key=lambda x: x["id"])


def _outcome_rows(rel: str, layer_key: str = "outcome") -> list[dict]:
    rows = []
    for r in _jsonl(ROOT / rel):
        outcome = r[layer_key]
        rows.append({"id": r["id"], "decision": "adopt" if outcome == "adopted" else "refuse", **({} if outcome == "adopted" else {"layer": outcome})})
    return sorted(rows, key=lambda x: x["id"])


def _gate_rows(rel: str) -> list[dict]:
    doc = json.loads((ROOT / rel).read_text(encoding="utf-8"))
    return sorted(({"id": r["id"], "decision": "refuse" if r["decision"] == "REJECT" else "adopt", **({"layer": "gate", "rules": r["rules"]} if r["decision"] == "REJECT" else {})}
                   for r in doc["results"]), key=lambda x: x["id"])


def _flag_rows() -> list[dict]:
    doc = json.loads((ROOT / "reports" / "v1.10" / "flag" / "flag_table.json").read_text(encoding="utf-8"))
    out = []
    for p in doc["patches"]:
        row = {"id": p["id"], "decision": p["decision"]}
        if p["layer"]:
            row["layer"] = p["layer"]
        if p["flag"]["flagged"]:
            row["flagged"] = True
            row["reasons"] = sorted(set(p["flag"]["static"] + p["flag"]["trace"]))
        out.append(row)
    return sorted(out, key=lambda x: x["id"])


